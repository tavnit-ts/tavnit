// Writes src/builtins/names.ts: the names of every built-in, as a static list.
//
// `builtinFilterNames` must not import the built-in registry (and through it re2js, yaml and the Temporal
// polyfill): a host that only wants the names would bundle ~130 KB gzip for them. The list is generated
// from the categories in dist/ and committed; `src/builtins/names.test.ts` fails when it drifts.
//
//   pnpm run build && node scripts/gen-builtin-names.mjs
import { writeFileSync } from "node:fs";
import { defaultBuiltins } from "../dist/categories/index.js";

const names = defaultBuiltins.flatMap((category) => Object.keys(category.filters));
const body = names.map((name) => `  ${JSON.stringify(name)},`).join("\n");
const out = `// Generated by scripts/gen-builtin-names.mjs from the built-in categories — do not edit.
// Run \`node scripts/gen-builtin-names.mjs\` after \`tsc\` when a built-in is added or removed;
// \`names.test.ts\` fails when this list and the categories differ.

/**
 * Names of every built-in function, in category order.
 * Hosts that register custom filters use this to keep built-ins from being
 * shadowed — a name listed here must not be re-registered.
 */
export const builtinFilterNames: readonly string[] = Object.freeze([
${body}
]);
`;
writeFileSync(new URL("../src/builtins/names.ts", import.meta.url), out);
console.log(`wrote ${names.length} names`);
